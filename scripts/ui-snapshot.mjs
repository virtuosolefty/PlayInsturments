import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
mkdirSync('review', { recursive: true });
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5187');
await page.getByRole('button', { name: "Let's play" }).click();
await page.screenshot({ path: 'docs/validation/piano-studio.png' });
await page.getByRole('button', { name: '3D Stage', exact: true }).click();
await page.locator('.roll-gl canvas').first().waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: 'docs/validation/piano-stage.png' });
await page.getByRole('group', { name: 'Practice instrument' }).getByRole('button', { name: 'Guitar', exact: true }).click();
await page.locator('.guitar-stage canvas').waitFor();
await page.waitForTimeout(300);
await page.screenshot({ path: 'docs/validation/guitar-stage.png' });
await page.getByRole('button', { name: '2D Trainer', exact: true }).click();
await page.screenshot({ path: 'docs/validation/guitar-studio.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(200);
await page.screenshot({ path: 'docs/validation/guitar-mobile.png' });
await page.getByRole('group', { name: 'Practice instrument' }).getByRole('button', { name: 'Piano', exact: true }).click();
await page.screenshot({ path: 'docs/validation/piano-mobile.png' });
console.log(JSON.stringify({ pageErrors: errors }));
await browser.close();
